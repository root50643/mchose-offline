import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const args = process.argv.slice(2);
const siteIndex = args.indexOf('--site');
const siteRoot = path.resolve(siteIndex < 0 ? fileURLToPath(new URL('../site', import.meta.url)) : args[siteIndex + 1]);
const checkOnly = args.includes('--check');
const excluded = new Set(['sw.js', 'offline-manifest.json', '.DS_Store', 'Thumbs.db']);
const sha256 = buffer => createHash('sha256').update(buffer).digest('hex');
async function collect(directory, relative = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
    const relativePath = relative ? `${relative}/${entry.name}` : entry.name;
    if (excluded.has(relativePath) || excluded.has(entry.name)) continue;
    if (entry.isSymbolicLink()) throw new Error(`Symbolic links cannot be published: ${relativePath}`);
    if (entry.isDirectory()) files.push(...await collect(path.join(directory, entry.name), relativePath));
    else if (entry.isFile()) {
      const contents = await readFile(path.join(directory, entry.name));
      files.push({ path: relativePath, url: relativePath.split('/').map(encodeURIComponent).join('/'), bytes: contents.length, sha256: sha256(contents) });
    }
  }
  return files;
}

if (!checkOnly) await mkdir(siteRoot, { recursive: true });
const files = (await collect(siteRoot)).sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
if (!files.some(file => file.path === 'index.html')) throw new Error('site/index.html is required before building the offline cache.');
const totalBytes = files.reduce((sum, file) => sum + file.bytes, 0);
if (totalBytes > 1024 ** 3) throw new Error('Published files exceed the GitHub Pages 1 GiB limit.');
const generatorSource = (await readFile(fileURLToPath(import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const version = sha256(JSON.stringify(files) + '\n' + generatorSource).slice(0, 20);
const manifest = { schemaVersion: 1, version, fileCount: files.length, totalBytes, files };
const manifestText = JSON.stringify(manifest, null, 2) + '\n';
const workerText = `/* Generated by tools/build-offline.mjs. Do not edit directly. */
'use strict';
const MANIFEST = ${JSON.stringify(manifest)};
const VERSION = MANIFEST.version;
const SCOPE = self.registration.scope;
const PREFIX = 'mchose-offline:' + encodeURIComponent(SCOPE) + ':';
const CACHE = PREFIX + VERSION;
const FILES = MANIFEST.files;
const absolute = value => new URL(value, SCOPE).href;
let cacheWork;

async function notify(data) {
  const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  for (const client of clients) {
    if (client.url.startsWith(SCOPE)) client.postMessage(data);
  }
}
function hex(buffer) { return Array.from(new Uint8Array(buffer), b => b.toString(16).padStart(2, '0')).join(''); }
async function status() {
  const cache = await caches.open(CACHE);
  let present = 0;
  for (const file of FILES) if (await cache.match(absolute(file.url))) present++;
  return { type: 'MCHOSE_OFFLINE_STATUS', version: VERSION, ready: present === FILES.length, loaded: present, total: FILES.length, totalBytes: MANIFEST.totalBytes };
}
async function fillCache() {
  const cache = await caches.open(CACHE);
  let next = 0;
  let loaded = 0;
  let loadedBytes = 0;
  let lastNotify = 0;
  let failure;
  async function download() {
    while (next < FILES.length && !failure) {
      const file = FILES[next++];
      try {
        const url = absolute(file.url);
        let response = await cache.match(url);
        if (!response) {
          response = await fetch(url, { cache: 'no-store', credentials: 'same-origin', redirect: 'error' });
          if (!response.ok || response.type === 'opaque') throw new Error('HTTP ' + response.status + ': ' + file.path);
          const bytes = await response.clone().arrayBuffer();
          if (bytes.byteLength !== file.bytes || hex(await crypto.subtle.digest('SHA-256', bytes)) !== file.sha256) {
            throw new Error('File integrity mismatch: ' + file.path);
          }
          await cache.put(url, response);
        }
        loaded++;
        loadedBytes += file.bytes;
        const now = Date.now();
        if (now - lastNotify > 250 || loaded === FILES.length) {
          lastNotify = now;
          await notify({ type: 'MCHOSE_OFFLINE_PROGRESS', version: VERSION, loaded, total: FILES.length, loadedBytes, totalBytes: MANIFEST.totalBytes });
        }
      } catch (error) { failure = error; }
    }
  }
  await Promise.all(Array.from({ length: Math.min(4, FILES.length) }, download));
  if (failure) throw failure;
  const result = await status();
  if (!result.ready) throw new Error('The complete offline cache is not available.');
  await notify({ ...result, type: 'MCHOSE_OFFLINE_READY' });
}
function ensureCache() {
  if (!cacheWork) cacheWork = fillCache().finally(() => { cacheWork = undefined; });
  return cacheWork;
}
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try {
      await ensureCache();
      if (!self.registration.active) await self.skipWaiting();
    } catch (error) {
      await caches.delete(CACHE);
      await notify({ type: 'MCHOSE_OFFLINE_ERROR', version: VERSION, message: error.message });
      throw error;
    }
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const result = await status();
    if (!result.ready) throw new Error('Refusing to activate an incomplete offline cache.');
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(PREFIX) && name !== CACHE).map(name => caches.delete(name)));
    await self.clients.claim();
    await notify({ ...result, type: 'MCHOSE_OFFLINE_READY' });
  })());
});
self.addEventListener('message', event => {
  if (event.source?.url && !event.source.url.startsWith(SCOPE)) return;
  const reply = data => {
    if (event.ports?.[0]) event.ports[0].postMessage(data);
    else event.source?.postMessage(data);
  };
  if (event.data?.type === 'MCHOSE_OFFLINE_GET_STATUS') event.waitUntil(status().then(reply));
  if (event.data?.type === 'MCHOSE_OFFLINE_REPAIR') {
    event.waitUntil(ensureCache().catch(error => notify({ type: 'MCHOSE_OFFLINE_ERROR', version: VERSION, message: error.message })));
  }
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) {
    event.respondWith(Promise.resolve(Response.error()));
    return;
  }
  if (!url.href.startsWith(SCOPE)) return;
  if (event.request.method !== 'GET' && event.request.method !== 'HEAD') {
    event.respondWith(Promise.resolve(new Response('The offline package only serves static files.', { status: 405 })));
    return;
  }
  const asRequested = response => event.request.method === 'HEAD'
    ? new Response(null, { status: response.status, statusText: response.statusText, headers: response.headers })
    : response;
  event.respondWith((async () => {
    if (url.pathname === new URL('offline-manifest.json', SCOPE).pathname) {
      return asRequested(new Response(JSON.stringify(MANIFEST), { headers: { 'Content-Type': 'application/json; charset=utf-8' } }));
    }
    const cache = await caches.open(CACHE);
    const key = new URL(url); key.search = ''; key.hash = '';
    const cached = await cache.match(key.href);
    if (cached) return asRequested(cached);
    let leaf = url.pathname.slice(url.pathname.lastIndexOf('/') + 1);
    try { leaf = decodeURIComponent(leaf); } catch {}
    if (event.request.mode === 'navigate' && (leaf === 'index.html' || !leaf.includes('.'))) {
      const index = await cache.match(absolute('index.html'));
      if (index) return asRequested(index);
    }
    return asRequested(new Response('This resource is not included in the complete offline package.', { status: 404, headers: { 'Content-Type': 'text/plain; charset=utf-8' } }));
  })());
});
`;

if (checkOnly) {
  const currentManifest = await readFile(path.join(siteRoot, 'offline-manifest.json'), 'utf8');
  const currentWorker = await readFile(path.join(siteRoot, 'sw.js'), 'utf8');
  if (currentManifest !== manifestText || currentWorker !== workerText) throw new Error('Offline manifest or service worker is stale. Run node tools/build-offline.mjs.');
  console.log(`Offline cache verified: ${files.length} files, ${totalBytes} bytes, version ${version}`);
} else {
  await writeFile(path.join(siteRoot, 'offline-manifest.json'), manifestText);
  await writeFile(path.join(siteRoot, 'sw.js'), workerText);
  console.log(`Offline cache built: ${files.length} files, ${totalBytes} bytes, version ${version}`);
}
